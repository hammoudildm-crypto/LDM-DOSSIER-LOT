-- =====================================================================
--  Table des dossiers de lot électroniques (eBMR) — à exécuter UNE FOIS
--  Supabase → SQL Editor → coller ce script → Run
-- =====================================================================

create table if not exists public.dossiers_lot (
  id          bigint generated by default as identity primary key,
  type        text default 'dossier',       -- 'dossier' (lot réel) | 'modele' (dossier type)
  nom         text,                          -- nom du modèle (quand type = 'modele')
  numero_lot  text,                          -- N° de lot (null pour un modèle)
  code_pf     text,
  numero_of   text,
  forme       text,                         -- 'Comprimés', 'Gélules', 'Crème'...
  statut      text default 'Brouillon',     -- Brouillon / En cours / Terminé / Libéré / Refusé
  date_fab    date,
  contenu     jsonb not null default '{}'::jsonb,   -- tout le dossier/modèle (saisie)
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- Si la table existe déjà en ancienne version, ajoute les colonnes manquantes :
alter table public.dossiers_lot add column if not exists type text default 'dossier';
alter table public.dossiers_lot add column if not exists nom  text;
alter table public.dossiers_lot alter column numero_lot drop not null;

create index if not exists idx_dossiers_lot_updated on public.dossiers_lot (updated_at desc);
create index if not exists idx_dossiers_lot_lot     on public.dossiers_lot (numero_lot);
create index if not exists idx_dossiers_lot_type    on public.dossiers_lot (type);

-- Mise à jour automatique de updated_at à chaque modification
create or replace function public.touch_dossiers_lot()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists trg_touch_dossiers_lot on public.dossiers_lot;
create trigger trg_touch_dossiers_lot
  before update on public.dossiers_lot
  for each row execute function public.touch_dossiers_lot();

-- Sécurité au niveau ligne (RLS).
-- Politique permissive (comme les autres tables de l'app, protégées par la clé).
-- Tu peux la restreindre plus tard (ex. réserver la suppression/libération à certains rôles).
alter table public.dossiers_lot enable row level security;

drop policy if exists "dossiers_lot_all" on public.dossiers_lot;
create policy "dossiers_lot_all"
  on public.dossiers_lot
  for all
  to anon, authenticated
  using (true)
  with check (true);


-- =====================================================================
--  Catalogue des PRODUITS (données de référence de l'IF par produit)
--  Alimente la liste déroulante « Produit à fabriquer » et le
--  gestionnaire de produits de l'application.
-- =====================================================================
create table if not exists public.produits_ref (
  id          bigint generated by default as identity primary key,
  nom         text not null unique,           -- nom affiché (= clé du catalogue)
  forme       text,
  ref_if      text,
  contenu     jsonb not null default '{}'::jsonb,   -- entete, amm, signataires, formule, mats, exc, equip…
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create index if not exists idx_produits_ref_nom on public.produits_ref (nom);

